import assert from 'node:assert/strict';
import {chromium} from 'playwright';

const origin=process.env.HEADER_SEARCH_ORIGIN||'http://127.0.0.1:4173';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
try{
 const page=await browser.newPage({viewport:{width:1600,height:960}});
 const indexRequests=[];
 page.on('request',r=>{if(/\/(?:toolbar-search|search-index)\./.test(new URL(r.url()).pathname))indexRequests.push(r.url());});
 await page.goto(origin+'/pages/about.html');
 const trigger=page.locator('#header-search-trigger'),panel=page.locator('#header-site-search'),input=panel.getByRole('searchbox');
 await trigger.waitFor();
 assert.deepEqual(indexRequests,[],'Search data and matcher stay off the first load');
 await trigger.press('Enter');assert(await input.evaluate(i=>i===document.activeElement));
 await input.fill('ریه');
 await panel.getByRole('button',{name:'نمایش همه نتایج'}).click();assert.ok(await panel.locator('li').count()>6);
 await input.fill('كليه');
 await panel.locator('a[href="/topics/nephrology/"]').waitFor();
 await input.focus();await input.press('ArrowDown');assert(await panel.locator('a').first().evaluate(a=>a===document.activeElement));
 await page.keyboard.press('Escape');assert(await panel.isHidden());assert(await trigger.evaluate(b=>b===document.activeElement));
 await page.locator('[data-language-toggle]').click();
 assert.equal(await trigger.getAttribute('aria-label'),'Search the site');
 await trigger.click();await input.fill('Spirometry Lab');
 const spirometry=panel.getByRole('link',{name:/spirometry lab/i}).first();
 await spirometry.waitFor();
 await input.fill('never-matches-zxq');await panel.getByRole('status').getByText('No results found.').waitFor();
 await input.fill('asthma');
 const article=panel.locator('a[href^="/articles/"]').first();
 await article.waitFor();
 assert.ok((await article.locator('.search-snippet').innerText()).length>10);
 assert.equal(await article.locator('small').innerText(),'Article');
 await page.locator('[data-theme-toggle]').click();
 await trigger.click();
 assert.ok(await panel.isVisible());
 assert.notEqual(await panel.evaluate(el=>getComputedStyle(el).color),await panel.evaluate(el=>getComputedStyle(el).backgroundColor));
 const articlePath=await article.getAttribute('href');
 await article.click();await page.waitForURL(new URL(articlePath,origin).href);
 assert.equal(await page.locator('html').getAttribute('lang'),'en');
 await page.setViewportSize({width:320,height:740});
 await trigger.click();assert(await input.isVisible());
 const rect=await panel.boundingBox();assert.ok(rect.x>=0&&rect.x+rect.width<=321);
 await input.fill('spirometry');await panel.locator('a').first().waitFor();
 await input.press('Enter');await panel.waitFor({state:'hidden'});assert.notEqual(page.url(),origin+articlePath);
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 await mobile.goto(origin+'/pages/about.html');
 let attempts=0;
 await mobile.route('**/content/search-index.json',r=>++attempts===1?r.fulfill({status:503,body:''}):r.continue());
 await mobile.locator('#header-search-trigger').tap();
 await mobile.locator('#header-site-search input').fill('آسم');
 await mobile.getByRole('button',{name:'تلاش دوباره'}).click();
 await mobile.locator('#header-site-search a').first().waitFor();
 assert.equal(attempts,2);
 await mobile.locator('.mobile-menu>summary').tap();assert(await mobile.locator('#header-site-search').isHidden());
 assert.equal(await mobile.locator('.mobile-menu').evaluate(el=>el.open),true);
 console.log('PASS site search: on-demand index, Persian normalization, English articles and projects, navigation, keyboard, touch and mobile panel bounds.');
}finally{await browser.close();}
